export type M6011Row = {
  S: number; // ft
  R: number; // ft
  HT: number; // in, outside height
  WIDTH: number; // in, outside width
  fill: [number, number]; // ft, the fill it's for ("< 2" is [0, 2])
  Tt: number; // in
  Tb: number;
  TW: number;
  bars: { t1b1: number; t2: number; b2: number; w: number; c1: number; c2: number };
  d1: number; // number of d1 bars
  h1: number; // in
  h2: number;
  v1: number;
  v2: number;
  v3: number;
  cy: number; // CY/LF, barrel only
  lb: number; // LB/LF, barrel only
};

export const M6011_ROWS: M6011Row[] = ROWS.trim()
  .split("\n")
  .map((line) => {
    const p = line.trim().split(/\s+/);
    const fill: [number, number] = p[4] === "<2" ? [0, 2] : (p[4].split("-").map(Number) as [number, number]);
    const n = (k: number) => Number(p[k]);
    return {
      S: n(0),
      R: n(1),
      HT: ftIn(p[2]),
      WIDTH: ftIn(p[3]),
      fill,
      Tt: n(5),
      Tb: n(6),
      TW: n(7),
      bars: { t1b1: n(8), t2: n(9), b2: n(10), w: n(11), c1: n(12), c2: n(13) },
      d1: n(14),
      h1: ftIn(p[15]),
      h2: ftIn(p[16]),
      v1: ftIn(p[17]),
      v2: ftIn(p[18]),
      v3: ftIn(p[19]),
      cy: n(20),
      lb: n(21),
    };
  });

/** The standard's row for a single cell of clear span S and rise R (ft) under this fill, or null (a special design). */
export function m6011Row(cells: number, S: number, R: number, fill: number): M6011Row | null {
  if (Math.round(cells) !== 1) return null;
  const rows = M6011_ROWS.filter((r) => Math.abs(r.S - S) < 1e-9 && Math.abs(r.R - R) < 1e-9);
  // "< 2" is under 2 ft; the others include both ends, the lighter range first at a shared end.
  return rows.find((r) => (r.fill[0] === 0 ? fill < 2 : fill >= r.fill[0] - 1e-9 && fill <= r.fill[1] + 1e-9)) ?? null;
}
